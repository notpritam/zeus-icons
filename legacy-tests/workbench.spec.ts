test('Pro batch excludes free variants and supports a persistent review walkthrough', async ({ page }) => {
  await page.goto('/?review=pro-001');
  const dialog = page.getByRole('dialog');
  const detail = page.getByRole('region', { name: 'Selected Pro variant' });
  const queue = page.getByLabel('Pro review queue');
  await expect(queue.getByRole('button')).toHaveCount(100);
  await expect(queue).not.toContainText('Stroke Rounded');
  await expect(detail.getByRole('heading')).toHaveText('1st Bracket');
  await expect(detail.getByRole('link')).toHaveAttribute('href', 'https://hugeicons.com/icon/1st-bracket?style=solid-sharp');
  await expect(detail.locator('img')).toHaveCount(2);
  await expect.poll(() => detail.locator('img').evaluateAll(images => images.every(img => img instanceof HTMLImageElement && img.complete && img.naturalWidth > 0))).toBe(true);
  await detail.getByRole('button', { name: 'Mark reviewed' }).click();
  await expect(dialog.getByText('1 / 100', { exact: true })).toBeVisible();
  await detail.getByRole('button', { name: 'Next Pro variant' }).click();
  await expect(detail.getByRole('link')).toHaveAttribute('href', /style=stroke-sharp$/);
  await page.reload();
  await expect(dialog.getByText('1 / 100', { exact: true })).toBeVisible();
  await expect(detail.getByRole('button', { name: 'Reviewed ✓', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await queue.getByRole('button').last().click();
  await expect(detail.getByRole('link')).toHaveAttribute('href', 'https://hugeicons.com/icon/3-d-view?style=solid-sharp');
  await expect(detail.getByRole('button', { name: 'Next Pro variant' })).toBeDisabled();
  await dialog.getByRole('textbox', { name: 'Search Pro batch' }).fill('3d scale');
  await expect(queue.getByRole('button')).toHaveCount(9);
  const pending = page.waitForEvent('download');
  await dialog.getByRole('button', { name: 'Download review list' }).click();
  const download = await pending;
  const chunks: Buffer[] = [];
  for await (const chunk of await download.createReadStream()) chunks.push(chunk);
  const exported = JSON.parse(Buffer.concat(chunks).toString()) as { entries: { id: string; style: string }[]; reviewedIds: string[] };
  expect(exported.entries).toHaveLength(100);
  expect(exported.entries.every(entry => entry.style !== 'stroke-rounded')).toBe(true);
  expect(exported.reviewedIds).toEqual(['1st-bracket-solid-sharp']);
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(detail.getByRole('heading')).toBeVisible();
  expect(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true);
});

