test('SVG export headers, mapping, sanitization, persistence, review and download', async ({ page }) => {
  const dtdRequests: string[] = [];
  page.on('request', request => { if (request.url().includes('unused-svg.dtd')) dtdRequests.push(request.url()); });
  await open(page);
  await page.getByRole('button', { name: 'Import SVGs', exact: true }).click();
  const exportedSvg = `<?xml version="1.0" encoding="UTF-8"?>\n<!DOCTYPE svg PUBLIC "-//W3C//DTD SVG 1.1//EN" "https://example.com/unused-svg.dtd">\n${svg}`;
  await page.getByLabel('Choose SVG files').setInputFiles({ name: 'home-01.svg', mimeType: 'image/svg+xml', buffer: Buffer.from(exportedSvg) });
  await expect(page.getByText('1 of 1 mapped')).toBeVisible();
  await page.getByRole('button', { name: 'Import 1 icon', exact: true }).click();
  await expect(page.locator('.comparison-legend')).toContainText('Imported SVG');
  await expect(page.getByText('100.00% shape overlap')).not.toBeVisible();
  await page.getByRole('spinbutton', { name: 'Horizontal', exact: true }).fill('1.4');
  await page.getByRole('spinbutton', { name: 'Horizontal', exact: true }).press('Enter');
  await page.getByRole('button', { name: 'Mark reviewed', exact: true }).click();
  await expect(page.getByText('Saved in this browser')).toBeVisible();
  await page.reload();
  await expect(page.getByRole('button', { name: '✓ Reviewed', exact: true })).toBeVisible();
  await expect(page.getByRole('spinbutton', { name: 'Horizontal', exact: true })).toHaveValue('1.4');
  await expect(page.locator('.comparison-legend')).toContainText('Imported SVG');
  expect(await page.evaluate(() => 'svgPwned' in window)).toBe(false);
  const pendingDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download SVG', exact: true }).click();
  const download = await pendingDownload;
  expect(download.suggestedFilename()).toBe('home-01.svg');
  const stream = await download.createReadStream();
  const parts: Buffer[] = [];
  for await (const chunk of stream) parts.push(chunk);
  const content = Buffer.concat(parts).toString();
  expect(content).toContain('<rect');
  expect(content).not.toContain('<script');
  expect(content).not.toContain('invalid.example');
  expect(content).not.toContain('DOCTYPE');
  expect(dtdRequests).toEqual([]);
});
