import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { load } from 'cheerio';
import { unzipSync, strFromU8 } from 'fflate';
import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { HugeiconsIcon } from '@hugeicons/react';
import { readPackage, matchPackage } from './package-utils.mjs';
import { readWebsite } from './fetch-upstream.mjs';
import { readAliasReview, unresolvedArtwork } from './alias-review.mjs';

const output=path.resolve('public');
const readJson=async filename=>JSON.parse(await fs.readFile(path.join(output,filename),'utf8'));
const [catalog,manifest,snapshot,report,pkg]=await Promise.all([readJson('catalog.json'),readJson('manifest.json'),readJson('upstream-metadata.json'),readJson('audit.json'),readPackage()]);
const website=process.argv.includes('--live')?await readWebsite({refresh:true}):snapshot;
const mapping=matchPackage(website,pkg);
assert.deepEqual(mapping.missing,[],'Unmapped free website entries');
assert.deepEqual(mapping.unlisted,[],'Unlisted package geometry modules');
assert.equal(catalog.packageVersion,pkg.version,'Installed package version differs from generated catalogue');
assert.equal(manifest.packageVersion,pkg.version);
assert.equal(catalog.icons.length,pkg.modules.length,'Canonical package icons were lost or duplicated');
assert.equal(catalog.coverage.websiteCount,website.websiteCount);
assert.equal(catalog.coverage.packageCount,pkg.modules.length);
assert.equal(catalog.coverage.mappedCount,catalog.icons.length);
const aliasReview=await readAliasReview(pkg,Object.groupBy(mapping.matched,m=>m.module.exportName),{live:process.argv.includes('--live')});
const artworkDifferences=unresolvedArtwork(aliasReview);
assert.deepEqual(catalog.coverage.missingFromPackage,artworkDifferences,'Known website artwork differences were hidden');
assert.deepEqual(report.missingFromPackage,artworkDifferences);
assert.deepEqual(report.upstreamAliasReview,aliasReview);
assert.deepEqual(catalog.coverage.missingFromWebsite,[]);
assert.equal(new Set(catalog.icons.map(i=>i.id)).size,catalog.icons.length,'Duplicate icon ids');
assert.equal(new Set(catalog.icons.map(i=>i.exportName)).size,catalog.icons.length,'Duplicate canonical modules');
const moduleByName=new Map(pkg.modules.map(m=>[m.exportName,m]));
const groupByName=Object.groupBy(mapping.matched,m=>m.module.exportName);
const manifestById=new Map(manifest.icons.map(m=>[m.id,m]));
assert.equal(manifest.icons.length,catalog.icons.length);
assert.equal(manifest.icons.flatMap(m=>m.websiteAliases).length,website.websiteCount);
assert.deepEqual(new Set(manifest.icons.flatMap(m=>m.packageAliases)),new Set(pkg.modules.flatMap(m=>m.aliases)),'Package aliases were lost');
assert.deepEqual(catalog.categories.map(({id,name,sourceUrl,expectedCount})=>({id,name,sourceUrl,expectedCount})),website.categories.map(({id,name,sourceUrl,expectedCount})=>({id,name,sourceUrl,expectedCount})),'Website category names, order, or counts changed');
const expectedCategoryIds=new Set(website.categories.map(c=>c.id));
assert(website.icons.every(i=>expectedCategoryIds.has(i.category)),'Unknown upstream category');
const categoryDifferences=[];
for(const category of catalog.categories) {
  const rawCount=website.icons.filter(i=>i.category===category.id).length;
  assert.equal(rawCount,category.expectedCount,`Website count is inconsistent for ${category.id}`);
  const actualCount=catalog.icons.filter(i=>i.categories.includes(category.id)).length;
  assert.equal(actualCount,category.actualCount,`Local count differs for ${category.id}`);
  if(rawCount!==actualCount) categoryDifferences.push(`${category.name}: ${rawCount} website entries map to ${actualCount} unique package icons (website aliases are deduplicated).`);
}
assert.deepEqual(catalog.coverage.categoryMismatches,categoryDifferences,'Alias count differences are not fully reported');
assert.deepEqual(report.categoryAliasDifferences,categoryDifferences);
assert.deepEqual(report.unexpectedCategoryMismatches,[]);
const xmlNodes=svg=>{
  const $=load(svg,{xmlMode:true});
  const root=$('svg');assert.equal(root.length,1,'Expected exactly one SVG root');
  assert.equal(root.attr('viewBox'),'0 0 24 24');
  assert.equal(root.attr('fill'),'none');
  assert.equal(root.attr('width'),'24');
  assert.equal(root.attr('height'),'24');
  const attributes={...root.get(0).attribs};
  if(attributes.color==='currentColor') delete attributes.color;
  if(attributes.class==='') delete attributes.class;
  return {attributes,nodes:root.children().toArray().map(node=>({tag:node.name,attributes:{...node.attribs}}))};
};
const zipBuffer=await fs.readFile(path.join(output,'free-icons.zip'));
const zip=unzipSync(zipBuffer);
assert.equal(Object.keys(zip).length,catalog.icons.length+4,'Archive contains unexpected or missing files');
assert.equal(Object.keys(zip).filter(name=>name.startsWith('icons/')&&name.endsWith('.svg')).length,catalog.icons.length,'Archive SVG count differs');
assert.equal(strFromU8(zip['LICENSE-hugeicons.txt']),pkg.license,'Archive license differs from package license');
assert.equal(await fs.readFile(path.join(output,'LICENSE-hugeicons.txt'),'utf8'),pkg.license,'Public license differs from package license');
assert.deepEqual(JSON.parse(strFromU8(zip['manifest.json'])),manifest,'Archive mapping manifest differs');
assert.deepEqual(JSON.parse(strFromU8(zip['categories.json'])),catalog.categories,'Archive category manifest differs');
const localFilenames=await fs.readdir(path.join(output,'icons'));
const referenceFilenames=await fs.readdir(path.join(output,'reference'));
assert.equal(localFilenames.length,catalog.icons.length,'Unexpected local SVG files');
assert.equal(referenceFilenames.length,catalog.icons.length,'Unexpected reference files');
let nodeCount=0;
for(const icon of catalog.icons) {
  const module=moduleByName.get(icon.exportName);assert(module,`Unknown export ${icon.exportName}`);
  assert(/^[a-z0-9-]+$/.test(icon.id),`Unsafe local id ${icon.id}`);
  assert.equal(icon.localUrl,`/icons/${icon.id}.svg`);
  assert.equal(icon.referenceUrl,`/reference/${icon.id}.json`);
  assert.equal(icon.sourceUrl,`https://hugeicons.com/icon/${encodeURIComponent(manifestById.get(icon.id).websitePrimaryName)}?style=stroke-rounded`);
  const group=groupByName[icon.exportName];
  assert.deepEqual(icon.categories,[...new Set(group.map(m=>m.icon.category))],`Category assignment mismatch: ${icon.id}`);
  const mapped=manifestById.get(icon.id);assert(mapped,`Missing manifest entry: ${icon.id}`);
  assert.equal(mapped.exportName,module.exportName);
  assert.deepEqual(mapped.upstreamAliasReview,aliasReview.groups.find(g=>g.exportName===module.exportName)??null);
  assert.deepEqual(mapped.packageAliases,module.aliases);
  assert.deepEqual(mapped.websiteAliases,group.map(m=>({name:m.icon.name,category:m.icon.category,sourceUrl:`https://hugeicons.com/icon/${encodeURIComponent(m.icon.name)}?style=stroke-rounded`,matchedBy:m.matchedBy})),`Incomplete source aliases for ${icon.id}`);
  const [reference,localSvg]=await Promise.all([readJson(`reference/${icon.id}.json`),fs.readFile(path.join(output,'icons',`${icon.id}.svg`),'utf8')]);
  assert.deepEqual(reference,module.nodes,`Reference JSON differs from installed package: ${icon.id}`);
  // Independently render the official component to catch path, order, fill, opacity,
  // transform and camelCase-to-SVG mistakes in our exporter, for every single icon.
  const officialSvg=renderToStaticMarkup(createElement(HugeiconsIcon,{icon:module.nodes}));
  assert.deepEqual(xmlNodes(localSvg),xmlNodes(officialSvg),`SVG differs from official React geometry: ${icon.id}`);
  assert.equal(strFromU8(zip[`icons/${icon.id}.svg`]),localSvg,`Archive SVG differs: ${icon.id}`);
  nodeCount+=module.nodes.length;
}
// Regression protection for names where removing punctuation would pick wrong artwork.
const bySource=new Map(mapping.matched.map(m=>[m.icon.name,m.module.exportName]));
assert.equal(bySource.get('arrow-down-0-1'),'ArrowDownZeroOneIcon');
assert.equal(bySource.get('arrow-down-01'),'ArrowDown01Icon');
assert.equal(bySource.get('arrow-up-0-1'),'ArrowUpZeroOneIcon');
assert.equal(bySource.get('arrow-up-01'),'ArrowUp01Icon');
const result={status:'passed',verifiedAt:new Date().toISOString(),packageVersion:pkg.version,websiteEntries:website.websiteCount,canonicalSvgFiles:catalog.icons.length,categories:catalog.categories.length,verifiedSvgNodes:nodeCount,websiteAliases:website.websiteCount-catalog.icons.length,missingPackageExports:0,confirmedWebsiteDesignConflicts:aliasReview.groups.filter(g=>g.status==='confirmed-design-conflict').length,unverifiedWebsitePreviewDifferences:aliasReview.groups.filter(g=>g.status==='unverified-raster-difference').length,unexpectedCategoryMismatches:0,explainedCategoryCountDifferences:categoryDifferences.length,zipSha256:createHash('sha256').update(zipBuffer).digest('hex'),liveWebsiteChecked:process.argv.includes('--live')};
if(process.argv.includes('--write-report')) await fs.writeFile(path.join(output,'audit.json'),JSON.stringify({...report,verification:result},null,2)+'\n');
console.log(JSON.stringify(result,null,2));
