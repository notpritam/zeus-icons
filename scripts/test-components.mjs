import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { resolve, join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { execFileSync } from 'node:child_process';
import { componentName, componentSource, componentUsage } from '../src/lib/component-source.ts';

const root = resolve(import.meta.dirname, '..');
const consumer = join(root, '.local/package-consumer');
const require = createRequire(join(consumer, 'package.json'));
const ts = require('typescript');
const name = componentName('home-01', 'duotone-rounded', 'Home01Icon');
const svg = (await readFile(join(root, 'public/traced/svg/home-01-duotone-rounded.svg'), 'utf8')).replace('width="24"', 'width="48"').replace('<svg ', '<svg color="#3464ab" opacity="0.5" ');
const generated = join(consumer, 'generated');
await mkdir(generated, { recursive: true });
const transpile = source => ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext, jsx: ts.JsxEmit.ReactJSX }, reportDiagnostics: true }).outputText;
const react = componentSource('React', name, svg, 'Source notice');
await writeFile(join(generated, `${name}.tsx`), react);
await writeFile(join(generated, 'react.mjs'), transpile(react));
const React = require('react');
const { renderToStaticMarkup } = require('react-dom/server');
const { default: Component } = await import(pathToFileURL(join(generated, 'react.mjs')));
const output = renderToStaticMarkup(React.createElement(Component, { size: 72, color: '#aabbcc', opacity: 0.8, title: 'Home' }));
for (const value of ['width="72"', 'height="72"', 'color="#aabbcc"', 'opacity="0.8"', '<title>Home</title>', 'fill-rule=', 'currentColor']) assert(output.includes(value), value);
assert(!output.includes('color="#3464ab"'));
const vueSource = componentSource('Vue', name, svg, 'Source notice');
await writeFile(join(generated, `${name}.vue`), vueSource);
const vue = require('@vue/compiler-sfc');
const { descriptor } = vue.parse(vueSource);
const vueCode = vue.compileScript(descriptor, { id: 'icon-test', inlineTemplate: true }).content;
await writeFile(join(generated, 'vue.mjs'), transpile(vueCode));
const { default: VueComponent } = await import(pathToFileURL(join(generated, 'vue.mjs')));
const vueOutput = await require('@vue/server-renderer').renderToString(require('vue').createSSRApp(VueComponent, { size: 72, color: '#aabbcc', opacity: 0.8 }));
assert(vueOutput.includes('width="72"')); assert(vueOutput.includes('fill-rule='));
const svelteSource = componentSource('Svelte', name, svg, 'Source notice');
const svelte = require('svelte/compiler').compile(svelteSource, { filename: `${name}.svelte`, generate: 'server' });
assert.equal(svelte.warnings.filter(w => !w.code.startsWith('a11y')).length, 0);
await writeFile(join(generated, 'svelte.mjs'), svelte.js.code);
const { default: SvelteComponent } = await import(pathToFileURL(join(generated, 'svelte.mjs')));
const { render } = await import(pathToFileURL(require.resolve('svelte/server')));
const svelteOutput = render(SvelteComponent, { props: { size: 72, color: '#aabbcc', opacity: 0.8 } }).body;
assert(svelteOutput.includes('width="72"')); assert(svelteOutput.includes('fill-rule='));
await writeFile(join(generated, 'native.tsx'), componentSource('React native', name, svg, 'Source notice'));
await writeFile(join(generated, 'package.tsx'), `import { Home01SolidRoundedIcon } from 'zeus-icons/solid-rounded/Home01SolidRoundedIcon';\nimport type { Ref } from 'react';\nconst ref: Ref<SVGSVGElement> = { current: null };\nexport const icon = <Home01SolidRoundedIcon size={32} color="red" opacity={0.5} ref={ref} aria-label="Home" />;\n`);
await writeFile(join(generated, 'tsconfig.json'), JSON.stringify({ compilerOptions: { strict: true, skipLibCheck: true, jsx: 'react-jsx', target: 'ES2022', module: 'ESNext', moduleResolution: 'bundler', noEmit: true }, include: ['*.tsx'] }));
execFileSync(join(consumer, 'node_modules/.bin/tsc'), ['-p', join(generated, 'tsconfig.json')], { stdio: 'inherit' });
const angular = join(generated, 'angular');
await mkdir(angular, { recursive: true });
await writeFile(join(angular, `${name}.ts`), componentSource('Angular', name, svg, 'Source notice'));
await writeFile(join(angular, 'example.ts'), componentUsage('Angular', name, { size: 72, color: '#aabbcc', opacity: 0.8 }));
await writeFile(join(angular, 'tsconfig.json'), JSON.stringify({ compilerOptions: { strict: true, skipLibCheck: true, target: 'ES2022', module: 'ESNext', moduleResolution: 'bundler', experimentalDecorators: true, outDir: './dist' }, angularCompilerOptions: { strictTemplates: true, compilationMode: 'partial' }, include: ['*.ts'] }));
execFileSync(join(consumer, 'node_modules/.bin/ngc'), ['-p', join(angular, 'tsconfig.json')], { stdio: 'inherit' });
console.log('React, Vue and Svelte SSR passed; React/React Native/package TypeScript and Angular AOT + consumer template compilation passed.');
